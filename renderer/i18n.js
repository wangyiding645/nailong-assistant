  var DICT = { 'zh-CN': zh, zh: zh, en: en };

  var current = 'zh-CN';

  function setLocale(l) {
    var s = String(l || '').toLowerCase();
    current = s.indexOf('en') === 0 ? 'en' : 'zh-CN';
    return current;
  }

  function t(key, vars) {
    var table = DICT[current] || zh;
    var s = table[key];
    if (s === undefined) s = (zh[key] !== undefined ? zh[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      });
    }
    return s;
  }

  function applyDom(where) {
    var scope = where || root.document;
    if (!scope || !scope.querySelectorAll) return 0;
    var n = 0;
    Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n]'), function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
      n++;
    });
    Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-title]'), function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
      n++;
    });
    Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-ph]'), function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
      n++;
    });
    return n;
  }

  root.WidgetI18n = {
    setLocale: setLocale,
    t: t,
    applyDom: applyDom,
    get locale() { return current; },
    dict: DICT
  };
